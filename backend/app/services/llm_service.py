"""LLM Provider abstraction and implementations for PolicyPilot RAG.

Supports real Google Gemini API generation with strict error mapping and security
boundaries, along with a deterministic Mock provider for offline automated testing.
"""

import logging
import os
import re
import threading
from abc import ABC, abstractmethod
from typing import Optional

from app.config import settings

logger = logging.getLogger(__name__)


# ============================================================================
# Custom LLM Exceptions
# ============================================================================


class LLMError(Exception):
    """Base exception for all LLM provider errors."""

    pass


class LLMAuthenticationError(LLMError):
    """Raised when API credentials are missing, invalid, or unauthorized."""

    pass


class LLMTimeoutError(LLMError):
    """Raised when an LLM provider request times out."""

    pass


class LLMRateLimitError(LLMError):
    """Raised when LLM quota or rate limits are exceeded."""

    pass


class LLMProviderError(LLMError):
    """Raised when the LLM provider fails due to server error or malformed payload."""

    pass


# ============================================================================
# Security helper: redact potential keys from error messages
# ============================================================================


def _sanitize_error_message(message: str) -> str:
    """Mask any potential API key tokens or secrets from user-facing error text."""
    # Redact patterns resembling AIza... (Gemini / Google API keys)
    sanitized = re.sub(r"AIza[0-9A-Za-z-_]{35}", "[REDACTED_API_KEY]", str(message))
    # Redact Bearer tokens
    sanitized = re.sub(r"Bearer\s+[0-9A-Za-z-_\.]+", "Bearer [REDACTED]", sanitized)
    return sanitized


# ============================================================================
# Base LLM Provider Abstraction
# ============================================================================


class BaseLLMProvider(ABC):
    """Abstract base class for all LLM generation providers."""

    @property
    @abstractmethod
    def model_name(self) -> str:
        """Return the unique model identifier."""
        pass

    @abstractmethod
    def generate(self, prompt: str, system_instruction: str) -> str:
        """Generate a natural language completion given a prompt and system instruction.

        Args:
            prompt: User context containing formatted evidence passages and question.
            system_instruction: System grounding rules and citation constraints.

        Returns:
            The raw text answer generated by the model.

        Raises:
            LLMAuthenticationError: If API credentials are missing or invalid.
            LLMTimeoutError: If request times out.
            LLMRateLimitError: If rate limit is hit.
            LLMProviderError: On provider failure or bad response.
        """
        pass


# ============================================================================
# Google Gemini Provider
# ============================================================================


class GeminiLLMProvider(BaseLLMProvider):
    """Production provider using Google Gemini API via official google-genai SDK."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        model_name: Optional[str] = None,
        timeout: Optional[float] = None,
    ):
        self._configured_api_key = api_key
        self._model_name = model_name or settings.llm_model
        self._timeout = timeout or settings.rag_request_timeout_seconds
        self._client = None
        self._lock = threading.Lock()

    @property
    def model_name(self) -> str:
        return self._model_name

    def _get_api_key(self) -> str:
        """Resolve API key strictly from settings or environment without logging it."""
        key = (
            self._configured_api_key
            or settings.gemini_api_key
            or os.environ.get("GEMINI_API_KEY")
        )
        if not key or not key.strip():
            raise LLMAuthenticationError(
                "Gemini API key is not configured. "
                "Set the GEMINI_API_KEY environment variable."
            )
        return key.strip()

    def _get_client(self):
        """Lazily initialize Google GenAI client."""
        if self._client is None:
            with self._lock:
                if self._client is None:
                    api_key = self._get_api_key()
                    try:
                        from google import genai

                        self._client = genai.Client(api_key=api_key)
                        logger.info(
                            "Initialized Gemini client with model: %s", self._model_name
                        )
                    except LLMAuthenticationError:
                        raise
                    except Exception as exc:
                        clean_err = _sanitize_error_message(str(exc))
                        logger.error(
                            "Failed to initialize Gemini client: %s", clean_err
                        )
                        raise LLMProviderError(
                            f"Failed to initialize Gemini client: {clean_err}"
                        ) from exc
        return self._client

    def generate(self, prompt: str, system_instruction: str) -> str:
        """Call Gemini API generate_content with grounding instruction and context."""
        client = self._get_client()
        try:
            from google.genai import errors, types

            config = types.GenerateContentConfig(
                system_instruction=system_instruction,
                temperature=0.0,
                max_output_tokens=1024,
            )

            response = client.models.generate_content(
                model=self._model_name,
                contents=prompt,
                config=config,
            )

            text = response.text
            if not text:
                raise LLMProviderError("Gemini returned an empty response.")
            return text.strip()

        except LLMError:
            raise
        except Exception as exc:
            msg = str(exc)
            clean_msg = _sanitize_error_message(msg)

            # Map status codes or error messages to specific LLM errors
            from google.genai import errors

            if isinstance(exc, errors.APIError):
                status_code = getattr(exc, "code", None)
                if status_code in (401, 403) or "API_KEY_INVALID" in msg:
                    raise LLMAuthenticationError(
                        f"Gemini authentication failed: {clean_msg}"
                    ) from exc
                if status_code == 429 or "RESOURCE_EXHAUSTED" in msg:
                    raise LLMRateLimitError(
                        f"Gemini rate limit or quota exceeded: {clean_msg}"
                    ) from exc
                if status_code in (408, 504) or "DEADLINE_EXCEEDED" in msg:
                    raise LLMTimeoutError(
                        f"Gemini request timed out: {clean_msg}"
                    ) from exc
                raise LLMProviderError(
                    f"Gemini API error ({status_code}): {clean_msg}"
                ) from exc

            # Catch socket timeouts or generic network timeouts
            if "timeout" in msg.lower() or "timed out" in msg.lower():
                raise LLMTimeoutError(
                    f"Request to Gemini timed out: {clean_msg}"
                ) from exc

            if (
                "auth" in msg.lower()
                or "unauthorized" in msg.lower()
                or "api_key" in msg.lower()
            ):
                raise LLMAuthenticationError(
                    f"Gemini authentication error: {clean_msg}"
                ) from exc

            logger.error("Gemini generation failed: %s", clean_msg)
            raise LLMProviderError(f"Gemini generation error: {clean_msg}") from exc


# ============================================================================
# Deterministic Mock Provider for Testing
# ============================================================================


class MockLLMProvider(BaseLLMProvider):
    """Deterministic mock LLM provider for fast, reproducible offline testing."""

    def __init__(
        self,
        model_name: str = "mock-policy-llm",
        default_response: Optional[str] = None,
    ):
        self._model_name = model_name
        self.default_response = default_response
        self.last_prompt: Optional[str] = None
        self.last_system_instruction: Optional[str] = None
        self.call_count: int = 0

        # Behavioral test flags
        self.simulate_timeout: bool = False
        self.simulate_rate_limit: bool = False
        self.simulate_auth_error: bool = False
        self.simulate_hallucinated_citations: bool = False
        self.simulate_abstention: bool = False
        self.simulate_malformed: bool = False

    @property
    def model_name(self) -> str:
        return self._model_name

    def generate(self, prompt: str, system_instruction: str) -> str:
        self.call_count += 1
        self.last_prompt = prompt
        self.last_system_instruction = system_instruction

        if self.simulate_auth_error:
            raise LLMAuthenticationError("Mock: Invalid or missing API key.")
        if self.simulate_timeout:
            raise LLMTimeoutError("Mock: Request to upstream LLM timed out.")
        if self.simulate_rate_limit:
            raise LLMRateLimitError("Mock: Upstream rate limit reached (HTTP 429).")
        if self.simulate_malformed:
            return ""

        if self.simulate_abstention:
            return (
                "The uploaded policy documents do not contain sufficient evidence "
                "to answer this question."
            )

        if self.simulate_hallucinated_citations:
            return (
                "Employees receive 20 days of annual leave [S1], but sabbatical "
                "requires board approval [S99]."
            )

        if self.default_response:
            return self.default_response

        # Default intelligent mock: extract available source markers from prompt
        found_sources = re.findall(r"\[(S\d+)\]", prompt)
        if not found_sources:
            return (
                "The uploaded policy documents do not contain sufficient evidence "
                "to answer this question."
            )

        # If question contains a specific phrase, answer using [S1]
        primary_source = f"[{found_sources[0]}]"
        return (
            f"Based on documentation {primary_source}, standard annual leave "
            f"entitlement is granted to full-time personnel under company rules."
        )


# ============================================================================
# Singleton Factory
# ============================================================================

_provider_instance: Optional[BaseLLMProvider] = None
_factory_lock = threading.Lock()


def get_llm_provider(provider_type: Optional[str] = None) -> BaseLLMProvider:
    """Return configured LLM provider singleton."""
    global _provider_instance
    choice = (provider_type or settings.llm_provider).lower()

    if _provider_instance is None:
        with _factory_lock:
            if _provider_instance is None:
                if choice == "mock":
                    _provider_instance = MockLLMProvider()
                elif choice == "gemini":
                    _provider_instance = GeminiLLMProvider()
                else:
                    raise ValueError(f"Unsupported LLM provider: '{choice}'")
    return _provider_instance


def reset_llm_provider():
    """Reset the LLM provider singleton (useful in test teardown)."""
    global _provider_instance
    with _factory_lock:
        _provider_instance = None
